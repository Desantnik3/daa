def set_run_font(run, size=12, bold=False, italic=False):
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    run.font.color.rgb = RGBColor(0, 0, 0)
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:ascii"), "Times New Roman")
    rFonts.set(qn("w:hAnsi"), "Times New Roman")
    rFonts.set(qn("w:cs"), "Times New Roman")
    rFonts.set(qn("w:eastAsia"), "Times New Roman")


def p(doc, text="", *, size=12, bold=False, italic=False, center=False, space_after=6, space_before=0, first_line=True):
    para = doc.add_paragraph()
    pf = para.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    if first_line and text and not center:
        pf.first_line_indent = Cm(1.25)
    if center:
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf.first_line_indent = Cm(0)
    if text:
        run = para.add_run(text)
        set_run_font(run, size=size, bold=bold, italic=italic)
    return para


def mixed(doc, parts, *, center=False, space_after=6, first_line=True):
    para = doc.add_paragraph()
    pf = para.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    if first_line and not center:
        pf.first_line_indent = Cm(1.25)
    if center:
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf.first_line_indent = Cm(0)
    for text, bold, italic in parts:
        run = para.add_run(text)
        set_run_font(run, bold=bold, italic=italic)
    return para


def heading(doc, text):
    p(doc, text, size=13, bold=True, center=True, space_before=12, space_after=8, first_line=False)


def table_set_fonts(table, size=10):
    for row in table.rows:
        for cell in row.cells:
            for para in cell.paragraphs:
                para.paragraph_format.space_after = Pt(2)
                para.paragraph_format.space_before = Pt(2)
                para.paragraph_format.first_line_indent = Cm(0)
                if not para.runs:
                    run = para.add_run("")
                    set_run_font(run, size=size)
                for run in para.runs:
                    set_run_font(run, size=size, bold=run.bold or False)


def add_simple_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    for i, h in enumerate(headers):
        table.rows[0].cells[i].text = h
        for run in table.rows[0].cells[i].paragraphs[0].runs:
            run.bold = True
    for r_i, row in enumerate(rows):
        for c_i, val in enumerate(row):
            table.rows[r_i + 1].cells[c_i].text = str(val)
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    table_set_fonts(table, size=10)
    for cell in table.rows[0].cells:
        for run in cell.paragraphs[0].runs:
            set_run_font(run, size=10, bold=True)
    return table


